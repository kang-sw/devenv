#!/usr/bin/env node
// Builds dist/index.js: the extension as one ESM file with its npm runtime
// dependencies inlined, so a source checkout without node_modules still loads.
// Run `npm install && npm run bundle` in this package after every src/ edit and
// commit the output; the release host has no Node and ships the committed file.
//
// The first output line carries a hash of the bundle inputs. The Go launcher
// (piBundleInputHash in agents-plugin-tool/internal/wsagent) recomputes the same
// hash and loads the bundle only when it matches, so both sides must keep this
// exact algorithm: sorted package-relative slash paths of every src/**/*.ts and
// src/**/*.mjs file (web-search.ts statically imports web-search-helper.mjs),
// src/eff_large_wordlist.txt, package-lock.json and this script; digest =
// sha256 over "<path>\n<sha256 hex of the file bytes>\n" per input.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = dirname(dirname(fileURLToPath(import.meta.url)));
const wordlist = "src/eff_large_wordlist.txt";

function sourceFiles(dir) {
  return readdirSync(join(pkg, dir), { withFileTypes: true }).flatMap((ent) => {
    const rel = `${dir}/${ent.name}`;
    if (ent.isDirectory()) return sourceFiles(rel);
    return ent.isFile() && /\.(ts|mjs)$/.test(ent.name) ? [rel] : [];
  });
}

function bundleInputHash() {
  const inputs = [...sourceFiles("src"), wordlist, "package-lock.json", "scripts/bundle.mjs"];
  inputs.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const digest = createHash("sha256");
  for (const rel of inputs) {
    const file = createHash("sha256").update(readFileSync(join(pkg, rel))).digest("hex");
    digest.update(`${rel}\n${file}\n`);
  }
  return digest.digest("hex");
}

const outdir = join(pkg, "dist");
mkdirSync(outdir, { recursive: true });
const result = await build({
  metafile: true,
  // Keep generated module labels package-relative, even when producer tooling
  // supplies dependencies through a temporary node_modules symlink.
  absWorkingDir: pkg,
  preserveSymlinks: true,
  entryPoints: [join(pkg, "src", "index.ts")],
  outfile: join(outdir, "index.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  legalComments: "inline",
  logLevel: "warning",
  // Host-provided Pi packages must resolve through the running Pi (two
  // physical pi-tui copies break instanceof). pi-web-access is validated on
  // disk and imported only by the spawned web-search-helper.mjs.
  external: ["@earendil-works/pi-tui", "@earendil-works/pi-coding-agent", "@earendil-works/pi-ai", "pi-web-access"],
  banner: {
    js: [
      `// ws-pi-bundle-inputs: sha256-${bundleInputHash()}`,
      "// Generated by scripts/bundle.mjs from src/; do not edit.",
      // Inlined CommonJS dependencies call require() for Node builtins.
      'import { createRequire as __wsCreateRequire } from "node:module";',
      "const require = __wsCreateRequire(import.meta.url);",
    ].join("\n"),
  },
});
// The published boolbase 1.0.0 tarball omits its license file. This is the
// upstream repository LICENSE (https://github.com/fb55/boolbase/blob/master/LICENSE).
const boolbaseLicense = `Copyright (c) 2014-2015, Felix Boehm <me@feedic.com>

Permission to use, copy, modify, and/or distribute this software for any
purpose with or without fee is hereby granted, provided that the above
copyright notice and this permission notice appear in all copies.

THE SOFTWARE IS PROVIDED "AS IS" AND THE AUTHOR DISCLAIMS ALL WARRANTIES
WITH REGARD TO THIS SOFTWARE INCLUDING ALL IMPLIED WARRANTIES OF
MERCHANTABILITY AND FITNESS. IN NO EVENT SHALL THE AUTHOR BE LIABLE FOR
ANY SPECIAL, DIRECT, INDIRECT, OR CONSEQUENTIAL DAMAGES OR ANY DAMAGES
WHATSOEVER RESULTING FROM LOSS OF USE, DATA OR PROFITS, WHETHER IN AN
ACTION OF CONTRACT, NEGLIGENCE OR OTHER TORTIOUS ACTION, ARISING OUT OF
OR IN CONNECTION WITH THE USE OR PERFORMANCE OF THIS SOFTWARE.`;

const lock = JSON.parse(readFileSync(join(pkg, "package-lock.json"), "utf8"));
const roots = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const parts = input.replaceAll("\\", "/").split("/");
  const last = parts.lastIndexOf("node_modules");
  if (last < 0) continue;
  const end = last + (parts[last + 1].startsWith("@") ? 3 : 2);
  roots.add(parts.slice(0, end).join("/"));
}
const notices = ["Third-party licenses for dependencies inlined in dist/index.js.",
  "Host-provided and separately distributed dependencies are not included here.\n"];
for (const root of [...roots].sort()) {
  const metadata = lock.packages[root];
  if (!metadata?.version || !metadata.license) throw new Error(`Missing lockfile license metadata: ${root}`);
  const manifest = JSON.parse(readFileSync(join(pkg, root, "package.json"), "utf8"));
  if (manifest.version !== metadata.version) throw new Error(`Installed version differs from lockfile: ${root}`);
  const licenseFiles = readdirSync(join(pkg, root)).filter(name => /^licen[cs]e(?:[.-].*)?$/i.test(name)).sort();
  let license;
  if (licenseFiles.length) {
    license = licenseFiles.map(name => readFileSync(join(pkg, root, name), "utf8").trimEnd()).join("\n\n");
  } else if (manifest.name === "boolbase" && metadata.version === "1.0.0") {
    license = boolbaseLicense;
  } else {
    throw new Error(`Missing installed license text: ${root}`);
  }
  notices.push(`===== ${manifest.name}@${metadata.version} (${metadata.license}) =====\n${license}\n`);
}
writeFileSync(join(outdir, "THIRD_PARTY_NOTICES"), notices.join("\n") + "\n");
// word-chain-id.ts reads the wordlist relative to its own module URL.
copyFileSync(join(pkg, wordlist), join(outdir, "eff_large_wordlist.txt"));
