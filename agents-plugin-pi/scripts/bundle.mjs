#!/usr/bin/env node
// Builds dist/index.js: the extension as one ESM file with its npm runtime
// dependencies inlined, so a source checkout without node_modules still loads.
// Run `npm install && npm run bundle` in this package after every src/ edit and
// commit the output; the release host has no Node and ships the committed file.
//
// The first output line carries a hash of the bundle inputs. The Go launcher
// (piBundleInputHash in agents-plugin-tool/internal/wsagent) recomputes the same
// hash and loads the bundle only when it matches, so both sides must keep this
// exact algorithm: sorted package-relative slash paths of every src/**/*.ts and
// src/**/*.mjs file (web-search.ts statically imports web-search-helper.mjs),
// src/eff_large_wordlist.txt, package-lock.json and this script; digest =
// sha256 over "<path>\n<sha256 hex of the file bytes>\n" per input.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = dirname(dirname(fileURLToPath(import.meta.url)));
const wordlist = "src/eff_large_wordlist.txt";

function sourceFiles(dir) {
  return readdirSync(join(pkg, dir), { withFileTypes: true }).flatMap((ent) => {
    const rel = `${dir}/${ent.name}`;
    if (ent.isDirectory()) return sourceFiles(rel);
    return ent.isFile() && /\.(ts|mjs)$/.test(ent.name) ? [rel] : [];
  });
}

function bundleInputHash() {
  const inputs = [...sourceFiles("src"), wordlist, "package-lock.json", "scripts/bundle.mjs"];
  inputs.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const digest = createHash("sha256");
  for (const rel of inputs) {
    const file = createHash("sha256").update(readFileSync(join(pkg, rel))).digest("hex");
    digest.update(`${rel}\n${file}\n`);
  }
  return digest.digest("hex");
}

const outdir = join(pkg, "dist");
mkdirSync(outdir, { recursive: true });
await build({
  entryPoints: [join(pkg, "src", "index.ts")],
  outfile: join(outdir, "index.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  legalComments: "inline",
  logLevel: "warning",
  // Host-provided Pi packages must resolve through the running Pi (two
  // physical pi-tui copies break instanceof). pi-web-access is validated on
  // disk and imported only by the spawned web-search-helper.mjs.
  external: ["@earendil-works/pi-tui", "@earendil-works/pi-coding-agent", "@earendil-works/pi-ai", "pi-web-access"],
  banner: {
    js: [
      `// ws-pi-bundle-inputs: sha256-${bundleInputHash()}`,
      "// Generated by scripts/bundle.mjs from src/; do not edit.",
      // Inlined CommonJS dependencies call require() for Node builtins.
      'import { createRequire as __wsCreateRequire } from "node:module";',
      "const require = __wsCreateRequire(import.meta.url);",
    ].join("\n"),
  },
});
// word-chain-id.ts reads the wordlist relative to its own module URL.
copyFileSync(join(pkg, wordlist), join(outdir, "eff_large_wordlist.txt"));
